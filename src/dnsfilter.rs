fn load(db: &rusqlite::Connection) -> FilterConfig {
    state::get_setting(db, KEY)
        .and_then(|s| serde_json::from_str(&s).ok())
        .unwrap_or_default()
}

fn normalize_domain(s: &str) -> String {
    let mut d = s.trim().to_lowercase();
    if d.starts_with("*.") {
        d = d[2..].to_string();
    }
    d
}

fn valid_server(s: &str) -> bool {
    if let Some((ip, port)) = s.split_once('#') {
        cmd::is_ip(ip) && port.parse::<u16>().map(|p| p > 0).unwrap_or(false)
    } else {
        cmd::is_ip(s)
    }
}

pub fn render(cfg: &FilterConfig) -> String {
    let mut s = String::from("# generated by bianwrt — do not edit\n");
    if !cfg.enabled {
        s.push_str("# (disabled in panel)\n");
        return s;
    }
    for h in &cfg.hosts {
        let d = normalize_domain(&h.domain);
        if !d.is_empty() && cmd::is_ip(&h.ip) {
            s.push_str(&format!("address=/{}/{}\n", d, h.ip));
        }
    }
    for d in &cfg.blocked {
        let d = normalize_domain(d);
        if !d.is_empty() {
            s.push_str(&format!("address=/{}/0.0.0.0\n", d));
            s.push_str(&format!("address=/{}/::\n", d));
        }
    }
    for f in &cfg.forwards {
        let d = normalize_domain(&f.domain);
        if !d.is_empty() && valid_server(&f.server) {
            s.push_str(&format!("server=/{}/{}\n", d, f.server));
        }
    }
    s
}

pub async fn get(State(state): State<AppState>) -> Response {
    let cfg = load(&state.db.lock().unwrap());
    cmd::ok(json!({
        "config": cfg,
        "presets": presets(),
        "preview": render(&cfg),
        "path": CONF,
    }))
}

pub async fn put(
    State(state): State<AppState>,
    Json(cfg): Json<FilterConfig>,
) -> Response {
    if cfg.hosts.len() + cfg.blocked.len() + cfg.forwards.len() > 1000 {
        return cmd::err("条目总数超过上限（1000）");
    }
    for h in &cfg.hosts {
        if !cmd::is_domain(&normalize_domain(&h.domain)) || !cmd::is_ip(&h.ip) {
            return cmd::err(format!("静态域名条目无效：{} -> {}", h.domain, h.ip));
        }
    }
    for d in &cfg.blocked {
        if !cmd::is_domain(&normalize_domain(d)) {
            return cmd::err(format!("拦截域名无效：{}", d));
        }
    }
    for f in &cfg.forwards {
        if !cmd::is_domain(&normalize_domain(&f.domain)) || !valid_server(&f.server) {
            return cmd::err(format!("分流规则无效：{} -> {}", f.domain, f.server));
        }
    }
    let db = state.db.lock().unwrap();
    state::set_setting(&db, KEY, &serde_json::to_string(&cfg).unwrap());
    cmd::ok(json!({ "ok": true, "preview": render(&cfg) }))
}

pub async fn apply(State(state): State<AppState>) -> Response {
    let cfg = load(&state.db.lock().unwrap());
    let content = render(&cfg);
    let dir = std::path::Path::new(CONF).parent().unwrap();
    if !dir.is_dir() {
        return cmd::fail("未找到 /etc/dnsmasq.d，请先安装 dnsmasq：apt install dnsmasq");
    }
    if std::fs::write(CONF, &content).is_err() {
        return cmd::fail("写入 dnsmasq 配置失败（需要 root）");
    }
    let out = cmd::run("systemctl", &["restart", "dnsmasq.service"], 20).await;
    if !out.ok {
        let out2 = cmd::run("systemctl", &["restart", "dnsmasq"], 20).await;
        if !out2.ok {
            return cmd::fail(format!("dnsmasq 重启失败：{}", out.stderr.trim()));
        }
    }
    let _ = std::fs::write(state.data_dir.join("dnsmasq-filter-preview.conf"), &content);
    cmd::ok(json!({ "ok": true, "config": content }))
}
