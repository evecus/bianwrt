pub async fn config_get(State(state): State<AppState>) -> Response {
    let cfg = load(&state.db.lock().unwrap());
    cmd::ok(json!({
        "config": cfg,
        "preview": render(&cfg),
        "path": HOSTAPD_CONF,
        "hw_modes": [
            { "label": "2.4GHz (g)", "value": "g" },
            { "label": "5GHz (a)", "value": "a" },
            { "label": "2.4GHz (b)", "value": "b" }
        ],
    }))
}

pub async fn config_put(State(state): State<AppState>, Json(cfg): Json<ApConfig>) -> Response {
    if let Err(e) = validate(&cfg) {
        return cmd::err(e);
    }
    let db = state.db.lock().unwrap();
    state::set_setting(&db, KEY, &serde_json::to_string(&cfg).unwrap());
    cmd::ok(json!({ "ok": true, "preview": render(&cfg) }))
}

pub async fn apply(State(state): State<AppState>) -> Response {
    let cfg = load(&state.db.lock().unwrap());
    if !cfg.enabled {
        return cmd::err("请先在配置中启用 AP 再应用");
    }
    if let Err(e) = validate(&cfg) {
        return cmd::err(e);
    }
    if !cmd::which("hostapd") {
        return cmd::fail("未安装 hostapd：apt install hostapd");
    }
    let content = render(&cfg);
    let dir = std::path::Path::new(HOSTAPD_CONF).parent().unwrap();
    if std::fs::create_dir_all(dir).is_err() {
        return cmd::fail("无法创建 /etc/hostapd（需要 root）");
    }
    if std::fs::write(HOSTAPD_CONF, &content).is_err() {
        return cmd::fail("写入 hostapd.conf 失败（需要 root）");
    }
    #[cfg(unix)]
    {
        use std::os::unix::fs::PermissionsExt;
        let _ = std::fs::set_permissions(
            HOSTAPD_CONF,
            std::fs::Permissions::from_mode(0o600),
        );
    }
    let _ = std::fs::write(state.conf_dir.join("hostapd.conf"), &content);
    let out = cmd::run("systemctl", &["restart", "hostapd.service"], 20).await;
    if !out.ok {
        return cmd::fail(format!("hostapd 重启失败：{}", out.stderr.trim()));
    }
    cmd::ok(json!({ "ok": true, "config": content, "msg": "hostapd 已重启" }))
}

#[derive(Deserialize)]
pub struct ActionReq {
    pub op: String,
}

pub async fn action(Json(req): Json<ActionReq>) -> Response {
    if !matches!(req.op.as_str(), "start" | "stop" | "restart" | "enable" | "disable") {
        return cmd::err("操作须为 start / stop / restart / enable / disable");
    }
    let out = cmd::run("systemctl", &[&req.op, "hostapd.service"], 20).await;
    if !out.ok {
        return cmd::fail(format!("{} 失败：{}", req.op, out.stderr.trim()));
    }
    cmd::ok(json!({ "ok": true, "msg": format!("hostapd {} 成功", req.op) }))
}
