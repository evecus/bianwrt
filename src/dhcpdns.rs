use axum::extract::State;
use axum::response::{IntoResponse, Response};
use axum::Json;
use serde::{Deserialize, Serialize};
use serde_json::json;

use crate::state::{self, AppState};

#[derive(Serialize, Deserialize, Clone, Default)]
pub struct DhcpConfig {
    pub enabled: bool,
    pub interface: String,
    pub listen_dns: bool,
    pub domain: String,
    pub dhcp_start: String,
    pub dhcp_limit: u32,
    pub lease_hours: u32,
    pub gateway: String,
    pub dns_servers: Vec<String>,
    pub upstream_dns: Vec<String>,
    pub no_resolv: bool,
    pub cache_size: u32,
}

pub async fn get(State(state): State<AppState>) -> Response {
    let db = state.db.lock().unwrap();
    let cfg: DhcpConfig = state::get_setting(&db, "dhcp_config")
        .and_then(|s| serde_json::from_str(&s).ok())
        .unwrap_or_default();
    let mut statics = Vec::new();
    {
        let mut stmt = db
            .prepare("SELECT mac, ip, hostname FROM dhcp_static ORDER BY ip")
            .unwrap();
        for r in stmt
            .query_map([], |r| {
                Ok(json!({"mac": r.get::<_, String>(0)?, "ip": r.get::<_, String>(1)?, "hostname": r.get::<_, String>(2)?}))
            })
            .unwrap()
            .flatten()
        {
            statics.push(r);
        }
    }
    Json(json!({"config": cfg, "statics": statics})).into_response()
}

pub async fn put(State(state): State<AppState>, Json(cfg): Json<DhcpConfig>) -> Response {
    // validation
    if cfg.enabled {
        if cfg.dhcp_start.is_empty() || cfg.gateway.is_empty() {
            return (axum::http::StatusCode::BAD_REQUEST, "启用 DHCP 需填写起始地址与网关").into_response();
        }
        for (label, v) in [("起始地址", &cfg.dhcp_start), ("网关", &cfg.gateway)] {
            if !v.contains('.') || v.parse::<std::net::Ipv4Addr>().is_err() {
                return (axum::http::StatusCode::BAD_REQUEST, format!("{} 不是有效的 IPv4 地址", label))
                    .into_response();
            }
        }
    }
    for u in &cfg.upstream_dns {
        if u.parse::<std::net::IpAddr>().is_err() && !u.starts_with('/') {
            return (
                axum::http::StatusCode::BAD_REQUEST,
                format!("上游 DNS 无效: {}（应为 IP 或 /file 路径）", u),
            )
                .into_response();
        }
    }
    let db = state.db.lock().unwrap();
    state::set_setting(&db, "dhcp_config", &serde_json::to_string(&cfg).unwrap());
    Json(json!({"ok": true})).into_response()
}

pub async fn add_static(
    State(state): State<AppState>,
    Json(item): Json<serde_json::Value>,
) -> Response {
    let mac = item["mac"].as_str().unwrap_or_default().to_lowercase();
    let ip = item["ip"].as_str().unwrap_or_default().to_string();
    let hostname = item["hostname"].as_str().unwrap_or_default().to_string();
    if !is_mac(&mac) {
        return (axum::http::StatusCode::BAD_REQUEST, "MAC 地址格式无效").into_response();
    }
    if ip.parse::<std::net::Ipv4Addr>().is_err() {
        return (axum::http::StatusCode::BAD_REQUEST, "IP 地址无效").into_response();
    }
    let db = state.db.lock().unwrap();
    db.execute(
        "INSERT OR REPLACE INTO dhcp_static(mac,ip,hostname) VALUES(?1,?2,?3)",
        [&mac, &ip, &hostname],
    )
    .ok();
    Json(json!({"ok": true})).into_response()
}

pub async fn del_static(
    State(state): State<AppState>,
    axum::extract::Path(mac): axum::extract::Path<String>,
) -> Response {
    let db = state.db.lock().unwrap();
    db.execute("DELETE FROM dhcp_static WHERE mac=?1", [mac]).ok();
    Json(json!({"ok": true})).into_response()
}

fn is_mac(s: &str) -> bool {
    let p: Vec<&str> = s.split(':').collect();
    p.len() == 6 && p.iter().all(|x| x.len() == 2 && x.chars().all(|c| c.is_ascii_hexdigit()))
}

pub fn render_dnsmasq(cfg: &DhcpConfig, statics: &[(String, String, String)]) -> String {
    let mut s = String::from("# generated by bianwrt — do not edit\n");
    if !cfg.enabled {
        s.push_str("# (disabled in panel)\n");
        return s;
    }
    if !cfg.interface.is_empty() {
        s.push_str(&format!("interface={}\nbind-dynamic\n", cfg.interface));
    }
    if !cfg.domain.is_empty() {
        s.push_str(&format!("domain={}\n", cfg.domain));
    }
    // DHCP
    if !cfg.dhcp_start.is_empty() {
        let start_octets: Vec<&str> = cfg.dhcp_start.split('.').collect();
        let range_end = if start_octets.len() == 4 {
            let last: u32 = start_octets[3].parse().unwrap_or(100) + cfg.dhcp_limit.saturating_sub(1);
            format!("{}.{}.{}.{}", start_octets[0], start_octets[1], start_octets[2], last)
        } else {
            cfg.dhcp_start.clone()
        };
        s.push_str(&format!(
            "dhcp-range={},{},{},{}h\n",
            cfg.dhcp_start, range_end, cfg.dhcp_start, cfg.lease_hours
        ));
        s.push_str(&format!("dhcp-option=option:router,{}\n", cfg.gateway));
        let dns = if cfg.dns_servers.is_empty() {
            cfg.gateway.clone()
        } else {
            cfg.dns_servers.join(",")
        };
        s.push_str(&format!("dhcp-option=option:dns-server,{}\n", dns));
    }
    for (mac, ip, hn) in statics {
        if hn.is_empty() {
            s.push_str(&format!("dhcp-host={},{}\n", mac, ip));
        } else {
            s.push_str(&format!("dhcp-host={},{},{}\n", mac, ip, hn));
        }
    }
    // DNS
    if cfg.no_resolv && !cfg.upstream_dns.is_empty() {
        s.push_str("no-resolv\n");
        for u in &cfg.upstream_dns {
            s.push_str(&format!("server={}\n", u));
        }
    }
    s.push_str(&format!("cache-size={}\n", cfg.cache_size.max(0)));
    s.push_str("local-service\n");
    s
}

pub async fn apply(State(state): State<AppState>) -> Response {
    let (cfg, statics) = {
        let db = state.db.lock().unwrap();
        let cfg: DhcpConfig = state::get_setting(&db, "dhcp_config")
            .and_then(|s| serde_json::from_str(&s).ok())
            .unwrap_or_default();
        let mut statics = Vec::new();
        let mut stmt = db.prepare("SELECT mac,ip,hostname FROM dhcp_static").unwrap();
        for r in stmt
            .query_map([], |r| {
                Ok((
                    r.get::<_, String>(0)?,
                    r.get::<_, String>(1)?,
                    r.get::<_, String>(2)?,
                ))
            })
            .unwrap()
            .flatten()
        {
            statics.push(r);
        }
        (cfg, statics)
    };
    let content = render_dnsmasq(&cfg, &statics);
    // locate dnsmasq conf dir
    let candidates = ["/etc/dnsmasq.d", "/etc/dnsmasq.conf.d"];
    let dir = candidates.iter().find(|d| std::path::Path::new(d).is_dir());
    let Some(dir) = dir else {
        return (
            axum::http::StatusCode::INTERNAL_SERVER_ERROR,
            "未找到 /etc/dnsmasq.d，请先安装 dnsmasq: apt install dnsmasq",
        )
            .into_response();
    };
    let path = format!("{}/bianwrt.conf", dir);
    if std::fs::write(&path, &content).is_err() {
        return (axum::http::StatusCode::INTERNAL_SERVER_ERROR, "写入配置失败").into_response();
    }
    // ensure conf-dir enabled in main config
    let main_cfg = std::fs::read_to_string("/etc/dnsmasq.conf").unwrap_or_default();
    if !main_cfg.contains("conf-dir=/etc/dnsmasq.d") {
        let _ = std::fs::OpenOptions::new()
            .append(true)
            .open("/etc/dnsmasq.conf")
            .and_then(|mut f| std::io::Write::write_all(&mut f, b"\nconf-dir=/etc/dnsmasq.d,*.conf\n"));
    }
    let svc = if unit_exists("dnsmasq.service") { "dnsmasq.service" } else { "dnsmasq" };
    let st = tokio::process::Command::new("systemctl")
        .args(["restart", svc])
        .output()
        .await;
    let ok = st.map(|o| o.status.success()).unwrap_or(false);
    if !ok {
        return (axum::http::StatusCode::INTERNAL_SERVER_ERROR, "dnsmasq 重启失败，请检查配置").into_response();
    }
    let _ = std::fs::write(state.data_dir.join("dnsmasq-preview.conf"), &content);
    Json(json!({"ok": true})).into_response()
}

fn unit_exists(name: &str) -> bool {
    // synchronous helper: use std Command (called from async fn but cheap)
    std::process::Command::new("systemctl")
        .args(["list-unit-files", name])
        .output()
        .map(|o| {
            o.status.success()
                && String::from_utf8_lossy(&o.stdout).lines().count() > 1
                && !String::from_utf8_lossy(&o.stdout).contains("0 unit files listed")
        })
        .unwrap_or(false)
}

#[derive(Serialize)]
pub struct Lease {
    pub expires: i64,
    pub mac: String,
    pub ip: String,
    pub hostname: String,
}

pub async fn leases(State(_state): State<AppState>) -> Response {
    let mut out: Vec<Lease> = Vec::new();
    for p in [
        "/var/lib/misc/dnsmasq.leases",
        "/var/lib/dnsmasq/dnsmasq.leases",
    ] {
        if let Ok(content) = std::fs::read_to_string(p) {
            for line in content.lines() {
                let f: Vec<&str> = line.split_whitespace().collect();
                if f.len() >= 4 {
                    out.push(Lease {
                        expires: f[0].parse().unwrap_or(0),
                        mac: f[1].to_string(),
                        ip: f[2].to_string(),
                        hostname: f.get(3).unwrap_or(&"*").to_string(),
                    });
                }
            }
            break;
        }
    }
    // merge with static leases that have no active lease
    Json(serde_json::to_value(&out).unwrap()).into_response()
}
